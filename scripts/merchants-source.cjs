function normalizeBankHtml(html) {
  return html
    .replace(/<script\b[^<]*(?:(?!<\/script>)<[^<]*)*<\/script>/gi, "")
    .replace(/<style\b[^<]*(?:(?!<\/style>)<[^<]*)*<\/style>/gi, "")
    .replace(/<!--[\s\S]*?-->/g, "")
    .replace(/<[^>]+>/g, " ")
    .replace(/\b[0-9a-f]{16,}\b/gi, "")
    .replace(/\d{10,14}/g, "")
    .replace(/\s+/g, " ")
    .trim();
}

